import type { MonitoringSource } from '@/features/monitoring/types';

type Input = Omit<MonitoringSource, 'teamId' | 'availability'>;
const configured = (input: Input): MonitoringSource => ({
  ...input,
  teamId: 'KC',
  availability: input.requiredEnvironment.every((key) => Boolean(process.env[key]))
    ? 'LIVE'
    : 'CONFIGURED_BUT_UNAVAILABLE',
});
const x = (
  id: string,
  name: string,
  handle: string,
  tier: 1 | 2,
  authorityWeight: number,
): MonitoringSource =>
  configured({
    id,
    name,
    tier,
    platform: 'X',
    canonicalUrl: `https://x.com/${handle}`,
    ingestionMethod: 'X_API',
    deliveryStrategy: 'STREAM',
    cadenceSeconds: null,
    authorityWeight,
    active: true,
    notificationEligible: tier === 1,
    requiredEnvironment: ['X_BEARER_TOKEN', 'X_INGESTOR_ENABLED'],
    metadata: { handle },
  });
const web = (
  id: string,
  name: string,
  url: string,
  tier: 1 | 2 | 3,
  authorityWeight: number,
  feedUrl?: string,
  publishAll = false,
): MonitoringSource =>
  configured({
    id,
    name,
    tier,
    platform: feedUrl ? 'RSS' : 'WEB',
    canonicalUrl: url,
    ingestionMethod: feedUrl ? 'RSS_ATOM' : 'PUBLIC_PAGE',
    deliveryStrategy: 'POLL',
    cadenceSeconds: tier === 1 ? 300 : tier === 2 ? 600 : 1200,
    authorityWeight,
    active: true,
    notificationEligible: tier === 1,
    requiredEnvironment: feedUrl ? [] : ['PUBLIC_PAGE_INGESTION_ENABLED'],
    metadata: {
      feedUrl: feedUrl ?? null,
      requiresRobotsAndTermsReview: !feedUrl,
      publishAll,
    },
  });
const youtube = (
  id: string,
  name: string,
  url: string,
  authorityWeight: number,
): MonitoringSource =>
  configured({
    id,
    name,
    tier: 2,
    platform: 'YOUTUBE',
    canonicalUrl: url,
    ingestionMethod: 'YOUTUBE_WEBSUB',
    deliveryStrategy: 'WEBHOOK',
    cadenceSeconds: null,
    authorityWeight,
    active: true,
    notificationEligible: false,
    requiredEnvironment: [
      'YOUTUBE_API_KEY',
      'YOUTUBE_WEBSUB_CALLBACK_URL',
      'YOUTUBE_WEBSUB_ENABLED',
    ],
    metadata: {},
  });

