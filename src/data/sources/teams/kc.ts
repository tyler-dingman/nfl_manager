import type { SourceCategory, SourceDefinition, SourcePlatform } from '../types';

type KcSourceInput = {
  id: string;
  displayName: string;
  category: SourceCategory;
  trust: number;
  breaking?: number;
  analysis?: number;
  relevance?: number;
  platform?: SourcePlatform;
  handle?: string;
  url?: string;
  notes?: string;
  fanInterest?: number;
};

const source = ({
  id,
  displayName,
  category,
  trust,
  breaking = 65,
  analysis = 70,
  relevance = 100,
  platform = 'WEB',
  handle,
  url,
  notes,
  fanInterest,
}: KcSourceInput): SourceDefinition => ({
  id,
  name: displayName,
  displayName,
  team: 'KC',
  category,
  trustScore: trust,
  breakingNewsScore: breaking,
  analysisScore: analysis,
  teamRelevanceScore: relevance,
  fanInterestScore: fanInterest,
  platform,
  handle,
  url: url ?? (platform === 'X' && handle ? `https://x.com/${handle}` : undefined),
  enabled: true,
  priority: Math.max(breaking, analysis),
  notes,
});

