import { readFileSync, writeFileSync } from 'node:fs';
import { format, resolveConfig } from 'prettier';

// The supplied SVG is the only editable geometry source. Both renderers use this output.
const source = readFileSync(
  'public/images/team_branded_logos/down_distance_logo_vector.svg',
  'utf8',
);
const paths = [...source.matchAll(/<path id="([^"]+)" class="([^"]+)" d="([^"]+)"\/>/g)].map(
  ([, id, style, d]) => ({ id, style, d }),
);
if (paths.length !== 6) throw new Error('Master logo changed: review its semantic region mapping.');
const viewBox = source.match(/viewBox="([^"]+)"/)[1];
const raw = `// Generated by scripts/generate-team-logo.mjs. Do not edit geometry here.\nexport const LOGO_VIEW_BOX = ${JSON.stringify(viewBox)};\nexport const LOGO_PATHS = ${JSON.stringify(paths, null, 2)} as const;\n`;
const target = 'src/lib/branding/team-logo-paths.ts';
const output = await format(raw, { ...(await resolveConfig(target)), parser: 'typescript' });
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output)
    throw new Error('Run npm run logo:generate to update the master geometry.');
} else writeFileSync(target, output);
